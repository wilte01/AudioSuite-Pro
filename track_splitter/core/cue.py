"""cue.py — write a CUE sheet describing the split source.

The sheet describes the **source image** with one ``INDEX 01`` per detected
track start, not the files just written: a sheet over the outputs would carry a
zero offset for every track and could not re-create the split.  This way
``audiosuite cue split`` on the source reproduces the same tracks, and the
sheet round-trips through ``audio_suite_shared.cue_parser`` with the offsets
the split used.

Changed in 2.5.0: new module (PLAN_2026-11-03_2.5.0_feature_wave_1.md F-E4).
"""

from __future__ import annotations

from pathlib import Path

from audio_suite_shared.cue_generator import CueFileSpec, TrackSpec, build_cue

from .models import Track

#: Written as a sheet-level ``REM`` (``build_cue`` adds the ``REM`` token) so a
#: reader can tell where the sheet came from without guessing at the file's
#: provenance.
GENERATOR_REM = "Generated by AudioSuite-Pro Track Splitter"


def build_track_cue(
    *,
    source_name: str,
    tracks: list[Track],
    title: str = "",
    performer: str = "",
) -> str:
    """Build the CUE sheet text for a split of *source_name*.

    Args:
        source_name: The source file's name (the ``FILE`` token).
        tracks: The plan's tracks; each ``start_ms`` becomes an ``INDEX 01``,
            quantised to the format's own frames (75 per second), so a parsed
            offset can differ from the plan by up to one frame.
        title: Album title from the source's tags, when it has one.
        performer: Album artist from the source's tags, when it has one.

    Returns:
        The sheet text, ending with one newline.
    """
    specs = tuple(
        TrackSpec(
            number=track.number,
            title=track.title,
            performer=performer,
            start_ms=track.start_ms,
        )
        for track in tracks
    )
    return build_cue(
        title=title,
        performer=performer,
        rem=(GENERATOR_REM,),
        files=(CueFileSpec(filename=source_name, tracks=specs),),
    )


def write_track_cue(path: Path, sheet: str) -> Path:
    """Write *sheet* to *path* as UTF-8 text.

    Args:
        path: Destination ``.cue`` file.
        sheet: Text from :func:`build_track_cue`.

    Returns:
        *path*.

    Raises:
        OSError: The file cannot be written.
    """
    payload = sheet if sheet.endswith("\n") else f"{sheet}\n"
    path.write_text(payload, encoding="utf-8", newline="")
    return path
