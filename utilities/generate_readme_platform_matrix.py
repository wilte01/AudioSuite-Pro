#!/usr/bin/env python3
"""
generate_readme_platform_matrix.py

Regenerates the platform-support matrix block in the repository README.md from
the declaration in ``audio_suite_shared/platform_support.py`` (plan iteration 5,
item G1, audit #20).

The declaration is the single source of truth: every platform-conditional
branch in first-party code is classified there, and
``audio_suite_shared/tests/test_platform_support.py`` fails if a branch exists
in the tree that is not declared (or if a declared branch has drifted or
multiplied).  This script only *renders* that declaration, so the README can
never quietly disagree with the code.

Usage:
    python utilities/generate_readme_platform_matrix.py

Run this after editing ``PLATFORM_BRANCHES`` in
``audio_suite_shared/platform_support.py``.  The block between the PLATFORM
MATRIX markers is the only part of README.md this script touches.

Conventions (AGENTS.md "Utility Script Markers"): ASCII-only [START] / [OK] /
[ERROR] / [DONE] status markers on stdout/stderr.

Changed in 2.1.0: reads only first-party manifests.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
README = REPO_ROOT / "README.md"

BEGIN_MARK = "<!-- PLATFORM MATRIX: BEGIN"
END_MARK = "<!-- PLATFORM MATRIX: END"
END_SUFFIX = " -->"


def render_platform_matrix() -> str:
    """Build the complete marker-enclosed README matrix block.

    Returns:
        The replacement block including both markers: the anti-over-claim
        caveat, the per-tier summary, the per-tool consequence, and the full
        branch enumeration table.
    """
    from audio_suite_shared.platform_support import (
        MATRIX_CAVEAT,
        PLATFORM_BRANCHES,
        PORTABLE_CORE,
        TIER_TITLES,
        WINDOWS_ONLY,
        render_matrix_table,
        render_tier_summary,
        tool_tier,
        windows_only_tools,
    )
    from audio_suite_shared.tool_plugin import get_registry

    tools = get_registry().first_party
    windows_only = windows_only_tools()
    portable = [
        manifest.name for manifest in tools if tool_tier(manifest.id) == PORTABLE_CORE
    ]

    lines = [
        f"{BEGIN_MARK} — generated by utilities/generate_readme_platform_matrix.py"
        " from audio_suite_shared/platform_support.py; re-run the script after"
        " editing the declaration; do not edit the table by hand. -->",
        "",
        "#### What is verified, and what is not",
        "",
        MATRIX_CAVEAT,
        "",
        "#### Tool tiers",
        "",
        f"* **{TIER_TITLES[WINDOWS_ONLY]}** — "
        + ", ".join(f"`{tool}`" for tool in windows_only)
        + (
            ". The CD subsystem it drives (Win32 SCSI pass-through, drive"
            " enumeration) has no portable implementation; the tool fails"
            " fast with a named missing requirement rather than degrading"
            " silently."
        ),
        f"* **{TIER_TITLES[PORTABLE_CORE]}** — the other "
        f"{len(portable)} of {len(tools)} tools. Each has no"
        " platform-conditional code in its own package at all, so its"
        " non-Windows CLI path is the same code path as on Windows.",
        "",
        "#### Branch enumeration",
        "",
        render_tier_summary(),
        "",
        f"Every one of the {len(PLATFORM_BRANCHES)} distinct branches below was"
        " found by an AST scan of the first-party tree that skips comments and"
        " string literals; `audio_suite_shared/tests/test_platform_support.py`"
        " fails if a branch is added, removed or duplicated without"
        " re-classifying it here.",
        "",
        render_matrix_table(),
        "",
        f"{END_MARK} -->",
    ]
    return "\n".join(lines)


def main() -> int:
    """Regenerate the README platform-matrix block in place."""
    print("[START] Regenerating the README.md platform matrix")
    block = render_platform_matrix()
    if not block:
        print("[ERROR] platform matrix render produced an empty block")
        return 1

    text = README.read_text(encoding="utf-8")
    begin = text.find(BEGIN_MARK)
    end = text.find(END_MARK)
    if begin == -1 or end == -1 or end < begin:
        print("[ERROR] PLATFORM MATRIX markers not found in README.md")
        return 1
    end = end + len(END_MARK) + len(END_SUFFIX)

    # Keep the file's existing line terminator (AGENTS.md line-ending rule):
    # the generated block may use \n, so normalise it to the host file's
    # terminator before splicing.
    terminator = "\r\n" if "\r\n" in text else "\n"
    block = block.replace("\n", terminator)
    new_text = text[:begin] + block + text[end:]
    README.write_text(new_text, encoding="utf-8", newline="")

    row_count = sum(1 for line in block.splitlines() if line.startswith("| "))
    print(f"[OK] Platform matrix regenerated: {row_count - 1} branch rows")
    print("[DONE]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
