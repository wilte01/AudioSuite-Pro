from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent

#: The plan's base commit; every file changed since here must be annotated.
#: Updated for the Sprint 4 work window (D53): set to 2f6be06 (the 1.3.0
#: release tip) so only the 1.4.0 change set requires notes. Earlier work is
#: documented in its own plans and CHANGELOG.md, so it does not require
#: per-file notes here.
BASE_COMMIT = "2f6be06"

#: The exact marker D14 requires in each annotated file.
NOTE_MARKER = "Changed in 1.4.0"

#: First-party code/config formats that carry the note.
CODE_SUFFIXES: tuple[str, ...] = (
    ".py",
    ".toml",
    ".iss",
    ".ps1",
    ".ini",
    ".cfg",
    ".yml",
    ".yaml",
    ".gitignore",
)

#: Explicit exception categories. Every changed file must be either code or
#: one of these, so a new format cannot silently escape the scan.
EXCEPTION_SUFFIXES: tuple[str, ...] = (
    ".md",
    ".docx",
    ".pptx",
    ".json",
    ".lock",
    ".dll",
    "LICENSE",
    ".pyw",
    # 1.1.0 fetched audio fixtures (mutagen tests/data) - binary containers
    # with no comment syntax; provenance recorded in tests/data/ATTRIBUTION.md.
    # Still declared exceptions, but no longer the asserted non-empty category:
    # the 1.2.0 window starts after them (see the 1.2.0 note above).
    ".wv",
    ".ape",
    ".mpc",
    ".spx",
    ".dsf",
    # 1.4.0 licensed real-music BPM corpus (tests/data/bpm_corpus, CC0);
    # provenance and calibration are recorded in its ATTRIBUTION.md.
    ".ogg",
)

#: Categories asserted non-empty below - a comment-less or regenerated-binary
#: change is the very case the exception table exists for.
_REQUIRED_NON_EMPTY_EXCEPTIONS: tuple[tuple[str, tuple[str, ...]], ...] = (
    (
        "narrative documents (.md)",
        (".md",),
    ),
)


def changed_since_base() -> list[str]:
    """Return every tracked path that differs from the base commit.

    Returns:
        Sorted, forward-slashed repo-relative paths (worktree vs. base).

    Raises:
        subprocess.CalledProcessError: if ``git`` fails - e.g. the base commit
            is missing because the checkout is shallow.
    """
    result = subprocess.run(
        ["git", "-c", "core.autocrlf=false", "diff", "--name-only", BASE_COMMIT],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
        encoding="utf-8",
    )
    return sorted(line for line in result.stdout.splitlines() if line.strip())


@pytest.fixture(scope="module")
def changed() -> list[str]:
    """Files changed since the base commit, shared across the module."""
    return changed_since_base()


class TestPerFileChangeNote:
    """Every changed first-party code file carries the 1.0.1 note (D14)."""

    def test_scan_is_non_vacuous(self, changed: list[str]) -> None:
        """The base commit must be reachable and the code set non-empty."""
        code = [path for path in changed if path.endswith(CODE_SUFFIXES)]
        assert changed, (
            f"no files changed since {BASE_COMMIT} - is the checkout shallow?"
        )
        assert code, (
            f"no first-party code files changed since {BASE_COMMIT} - the note "
            "scan would pass vacuously"
        )

    def test_every_changed_code_file_carries_the_note(self, changed: list[str]) -> None:
        """Each changed code/config file names the release in a note."""
        missing = [
            path
            for path in changed
            if path.endswith(CODE_SUFFIXES)
            and NOTE_MARKER not in (REPO_ROOT / path).read_text(encoding="utf-8")
        ]
        assert not missing, (
            f"files changed since {BASE_COMMIT} without a {NOTE_MARKER!r} note "
            "(plan D14 / section 3.7):\n  " + "\n  ".join(missing)
        )

    def test_exception_categories_are_explicit_and_non_empty(
        self, changed: list[str]
    ) -> None:
        """Exception formats are declared, non-empty, and cover every change."""
        for label, suffixes in _REQUIRED_NON_EMPTY_EXCEPTIONS:
            matched = [path for path in changed if path.endswith(suffixes)]
            assert matched, (
                f"exception category {label} matched no changed file - the "
                "declared exception is stale, so the scan may be vacuous"
            )

        unclassified = [
            path
            for path in changed
            if not path.endswith(CODE_SUFFIXES)
            and not path.endswith(EXCEPTION_SUFFIXES)
        ]
        assert not unclassified, (
            "changed files are neither note-bearing code nor a declared "
            "exception - classify them in EXCEPTION_SUFFIXES:\n  "
            + "\n  ".join(unclassified)
        )
